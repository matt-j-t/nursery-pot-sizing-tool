// Fixed on import from the original upload: this file's import path said
// './logo_data.mjs' (underscore) but the data file it ships alongside is
// named 'logo-data.mjs' (hyphen) -- a straight filename mismatch that would
// 404 on load. Corrected below; no other line changed. `pointInLogo` was
// also not exported in the original -- exported here since potBuilder.js
// needs to call it directly per-vertex while building the interior floor's
// height field (see the comment above buildLogoEmboss for why this file's
// OTHER export, buildLogoEmboss, isn't the integration path used).
import { LOGO_POLYGONS } from './logo-data.mjs';

function pointInPoly(x, y, poly) {
    let inside = false;
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
          const [xi, yi] = poly[i], [xj, yj] = poly[j];
          if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) {
                  inside = !inside;
          }
    }
    return inside;
}
export function pointInLogo(x, y) {
    for (const p of LOGO_POLYGONS) if (pointInPoly(x, y, p)) return true;
    return false;
}

// Builds a small flat rectangular patch with the logo raised out of it --
// same grid-heightfield technique as everything else, so it needs no booleans
// and stitches into the floor the same way other patches have.
//
// NOT what potBuilder.js actually calls: the interior floor isn't its own
// independent mesh, it's generated by offsetting the exterior surface
// inward by wallT during solidify, so potBuilder.js instead calls
// pointInLogo() directly per-vertex while building that surface's height
// field and adds embossHeight locally where it's true. This function is
// kept as the standalone patch-building reference it was supplied as.
export function buildLogoEmboss({ widthM = 0.012, embossHeight = 0.0005, resX = 100 }) {
    const heightM = widthM * 0.42; // matches the logo's aspect ratio (~12mm x 5mm incl. padding used at parse time)
  const resY = Math.round(resX * (heightM / widthM));
    const xs = Array.from({length: resX}, (_, i) => -widthM/2 + widthM * i/(resX-1));
    const ys = Array.from({length: resY}, (_, j) => -heightM/2 + heightM * j/(resY-1));

  const verts = [];
    const idx = {};
    let c = 0;
    for (let j = 0; j < resY; j++) {
          for (let i = 0; i < resX; i++) {
                  const z = pointInLogo(xs[i], ys[j]) ? embossHeight : 0.0;
                  verts.push([xs[i], ys[j], z]);
                  idx[`${j}_${i}`] = c++;
          }
    }
    const faces = [];
    for (let j = 0; j < resY-1; j++) {
          for (let i = 0; i < resX-1; i++) {
                  faces.push([idx[`${j}_${i}`], idx[`${j}_${i+1}`], idx[`${j+1}_${i+1}`], idx[`${j+1}_${i}`]]);
          }
    }
    return { verts, faces, widthM, heightM, resX, resY };
}
